#!/usr/bin/env node
// Generates src/api/schema.generated.ts from the server's OpenAPI document
// (internal/api/openapi.yaml), so the dashboard's API types cannot drift from
// the spec the server embeds and serves.
//
//   pnpm run gen:api    rewrite the checked-in file
//   pnpm run check:api  regenerate into memory and fail if the checked-in
//                       file differs (run in CI after `pnpm install`)
//
// Offline: openapi-typescript reads the local YAML; nothing is fetched.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const specPath = resolve(here, '../../internal/api/openapi.yaml')
const outPath = resolve(here, '../src/api/schema.generated.ts')

const HEADER = `/**
 * generated — do not edit.
 *
 * Generated by openapi-typescript from internal/api/openapi.yaml.
 * Regenerate with \`pnpm run gen:api\`; CI runs \`pnpm run check:api\` and fails
 * when this file is stale. If a type here is wrong, fix the spec, not this file.
 */

`

async function generate() {
  const ast = await openapiTS(pathToFileURL(specPath), {
    // Only `required` makes a property non-optional. With the default (true),
    // a request field that merely has a server-side default (enabled,
    // retries) would become mandatory for callers.
    defaultNonNullable: false,
  })
  return HEADER + astToString(ast)
}

const check = process.argv.includes('--check')
const generated = await generate()

if (check) {
  let current = ''
  try {
    current = await readFile(outPath, 'utf8')
  } catch {
    // treated as stale below
  }
  if (current !== generated) {
    console.error(
      'src/api/schema.generated.ts is out of date with internal/api/openapi.yaml.\n' +
        'Run `pnpm run gen:api` in web/ and commit the result.',
    )
    process.exit(1)
  }
  console.log('src/api/schema.generated.ts matches internal/api/openapi.yaml')
} else {
  await writeFile(outPath, generated)
  console.log('wrote src/api/schema.generated.ts')
}
